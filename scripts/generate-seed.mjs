// Builds supabase/seed.sql from the menu transcribed in prototypes/shared/data.js,
// so the seed and the prototypes never drift apart. Run: node scripts/generate-seed.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const root = new URL('..', import.meta.url);
const src = readFileSync(new URL('prototypes/shared/data.js', root), 'utf8');
const sandbox = { window: {} };
vm.runInNewContext(src, sandbox);
const { sections } = sandbox.window.RIVERA;

// The prototypes carry demo-only descriptions and an "unavailable" example; the seed keeps
// only what is printed on the real menu.
const printedDesc = new Set(['أفوكادو']);
const englishName = { XL: 'XL' };

const q = (v) => (v == null || v === '' ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const n = (v) => (v == null ? 'null' : String(v));

const out = ['-- Generated by scripts/generate-seed.mjs. Do not edit by hand.', 'begin;'];
let itemCount = 0;
sections.forEach((s, si) => {
  out.push(`\n-- ${s.ar}`);
  out.push(`with s as (insert into public.sections (name_ar, name_en, icon, sort_order) values (${q(s.ar)}, ${q(s.en)}, ${q(s.icon)}, ${si}) returning id)`);
  // One statement per section: insert its items, then sizes and flavors keyed by sort order.
  const rows = s.items.map((it, ii) => `((select id from s), ${q(it.ar)}, ${q(englishName[it.ar] ?? it.en)}, ${q(printedDesc.has(it.ar) ? it.dar : null)}, ${q(printedDesc.has(it.ar) ? it.den : null)}, ${it.sizes ? 'null' : n(it.price)}, ${ii})`);
  out.push(`, i as (insert into public.items (section_id, name_ar, name_en, desc_ar, desc_en, price, sort_order) values\n  ${rows.join(',\n  ')}\n  returning id, sort_order)`);
  const sizes = [], flavors = [];
  s.items.forEach((it, ii) => {
    (it.sizes || []).forEach((z, zi) => sizes.push(`((select id from i where sort_order = ${ii}), ${q(z.ar)}, ${q(z.en)}, ${z.price}, ${zi})`));
    (it.extras || []).forEach((x, xi) => flavors.push(`((select id from i where sort_order = ${ii}), ${q(x.ar)}, ${q(x.en)}, ${xi})`));
  });
  const tail = [];
  if (sizes.length) tail.push(`z as (insert into public.item_sizes (item_id, name_ar, name_en, price, sort_order) values\n  ${sizes.join(',\n  ')})`);
  if (flavors.length) tail.push(`f as (insert into public.item_flavors (item_id, name_ar, name_en, sort_order) values\n  ${flavors.join(',\n  ')})`);
  if (tail.length) out.push(`, ${tail.join('\n, ')}`);
  out.push('select 1;');
  itemCount += s.items.length;
});
out.push('\ncommit;\n');

const dest = fileURLToPath(new URL('supabase/seed.sql', root));
writeFileSync(dest, out.join('\n'));
console.log(`Wrote ${dest}: ${sections.length} sections, ${itemCount} items`);
